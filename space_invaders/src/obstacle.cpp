Obstacle::Obstacle(Vector2 position)
{
    this->position = position;

    for(unsigned int row = 0; row < grid.size(); ++row)
    {
        for(unsigned int column = 0; column < grid[0].size(); ++column)
        {
            if(1 == grid[row][column])
            {
                float pos_x = position.x + column * BLOCK_WIDTH;
                float pos_y = position.y + row * BLOCK_HEIGHT;
                Block this_block = Block((Vector2){pos_x, pos_y});
                blocks.push_back(this_block);
            }
        }
    }
}

void Obstacle::Draw()
{
    for(auto& single_block: blocks)
    {
        single_block.Draw();
    }
}
